using FEDProtect.Core.Models;
using System.Text;
using System.Text.Json;

namespace FEDProtect.Core.Services;

public class OutputFormatter : IOutputFormatter
{
    public string FormatAsMarkdown(HardeningReport report, ThreatProfile profile)
    {
        var sb = new StringBuilder();

        sb.AppendLine($"# Security Checklist: {profile.Name}");
        sb.AppendLine();
        sb.AppendLine($"**Generated:** {report.GeneratedAt:yyyy-MM-dd HH:mm:ss} UTC");
        sb.AppendLine($"**Profile Version:** {profile.Version}");
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        sb.AppendLine("## Overview");
        sb.AppendLine();
        sb.AppendLine(profile.Description);
        sb.AppendLine();

        sb.AppendLine("## Threats & Mitigations");
        sb.AppendLine();

        foreach (var capability in profile.Capabilities)
        {
            sb.AppendLine($"### {capability.Name} [{capability.Severity.ToUpper()}]");
            sb.AppendLine();
            sb.AppendLine(capability.Description);
            sb.AppendLine();

            if (capability.Sources.Any())
            {
                sb.AppendLine("**Sources:**");
                foreach (var source in capability.Sources)
                {
                    sb.AppendLine($"- [{source.Title}]({source.Url}) - {source.Author} ({source.Date:yyyy-MM-dd})");
                }
                sb.AppendLine();
            }

            sb.AppendLine("**Recommended Actions:**");
            foreach (var mitigation in capability.Mitigations)
            {
                sb.AppendLine($"- [ ] **{mitigation.Action}** (Difficulty: {mitigation.Difficulty}, Effectiveness: {mitigation.Effectiveness})");
                sb.AppendLine($"  - {mitigation.Description}");
                if (!string.IsNullOrEmpty(mitigation.Resource))
                {
                    sb.AppendLine($"  - Resource: {mitigation.Resource}");
                }
                sb.AppendLine();
            }
        }

        if (!string.IsNullOrEmpty(profile.LegalNotes))
        {
            sb.AppendLine("## Legal Notes");
            sb.AppendLine();
            sb.AppendLine(profile.LegalNotes);
            sb.AppendLine();
        }

        sb.AppendLine("---");
        sb.AppendLine();
        sb.AppendLine("*Generated by FEDProtect - https://github.com/seloc0des/protest-hardener*");

        return sb.ToString();
    }

    public string FormatAsJson(HardeningReport report)
    {
        var options = new JsonSerializerOptions
        {
            WriteIndented = true
        };

        return JsonSerializer.Serialize(report, options);
    }
}
